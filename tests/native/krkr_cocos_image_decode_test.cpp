int main()
{
    cocos2d::Image rgba;
    if (!expect(rgba.initWithImageData(kRgbaPng, sizeof(kRgbaPng)), "RGBA PNG decode") ||
        !expect(rgba.getWidth() == 1 && rgba.getHeight() == 1, "RGBA dimensions") ||
        !expect(rgba.getDataLen() == 4, "RGBA decoded length") ||
        !expect(rgba.getData()[0] == 0xff && rgba.getData()[1] == 0x00 &&
                    rgba.getData()[2] == 0x00 && rgba.getData()[3] == 0xff,
                "RGBA pixel") ||
        !expect(rgba.getRenderFormat() == cocos2d::Texture2D::PixelFormat::RGBA8888,
                "RGBA render format"))
        return 1;

    cocos2d::Image palette;
    if (!expect(palette.initWithImageData(kPalettePng, sizeof(kPalettePng)),
                "palette PNG without tRNS decode") ||
        !expect(palette.getDataLen() == 4 && palette.getData()[0] == 0x00 &&
                    palette.getData()[1] == 0xff && palette.getData()[2] == 0x00 &&
                    palette.getData()[3] == 0xff,
                "palette opaque RGBA pixel"))
        return 1;

    std::array<unsigned char, 700> jpeg_bytes{};
    const size_t jpeg_size = decode_base64(kJpegBase64, jpeg_bytes.data(), jpeg_bytes.size());
    if (!expect(jpeg_size >= 2U && jpeg_bytes[0] == 0xff &&
                    jpeg_bytes[jpeg_size - 2U] == 0xff &&
                    jpeg_bytes[jpeg_size - 1U] == 0xd9,
                "JPEG fixture decode"))
        return 1;
    cocos2d::Image jpeg;
    if (!expect(jpeg.initWithImageData(jpeg_bytes.data(), static_cast<ssize_t>(jpeg_size)),
                "JPEG decode") ||
        !expect(jpeg.getWidth() == 1 && jpeg.getHeight() == 1, "JPEG dimensions") ||
        !expect(jpeg.getDataLen() == 4, "JPEG decoded length") ||
        !expect(jpeg.getData()[3] == 0xff, "JPEG alpha filler"))
        return 1;

    unsigned char* previous_data = rgba.getData();
    const ssize_t previous_length = rgba.getDataLen();
    const int previous_width = rgba.getWidth();
    const int previous_height = rgba.getHeight();
    const cocos2d::Image::Format previous_format = rgba.getFileType();
    if (!expect(!rgba.initWithImageData(kRgbaPng, sizeof(kRgbaPng) - 3U),
                "truncated PNG rejection") ||
        !expect(state_unchanged(rgba, previous_data, previous_length, previous_width,
                                 previous_height, previous_format),
                "PNG failure preserves state"))
        return 1;
    if (!expect(!rgba.initWithImageData(jpeg_bytes.data(), 12), "truncated JPEG rejection") ||
        !expect(state_unchanged(rgba, previous_data, previous_length, previous_width,
                                 previous_height, previous_format),
                "JPEG failure preserves state"))
        return 1;

    unsigned char raw_pixel[4] = {0xff, 0x00, 0x00, 0xff};
    if (!expect(!rgba.initWithRawData(raw_pixel, sizeof(raw_pixel), 16384, 16384, 8),
                "raw decoded byte ceiling") ||
        !expect(!rgba.initWithImageData(kOversizedPng, sizeof(kOversizedPng)),
                "PNG dimension ceiling"))
        return 1;

    // Exercise repeated longjmp/cleanup paths; this is intentionally bounded
    // and remains a compile/link seam until an Android runner is available.
    for (size_t length = 0U; length < sizeof(kRgbaPng); ++length)
        (void)rgba.initWithImageData(kRgbaPng, static_cast<ssize_t>(length));
    for (size_t length = 0U; length < 64U; ++length)
        (void)jpeg.initWithImageData(jpeg_bytes.data(), static_cast<ssize_t>(length));
    return 0;
}
