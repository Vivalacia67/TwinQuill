int base64_value(char value)
{
    if (value >= 'A' && value <= 'Z') return value - 'A';
    if (value >= 'a' && value <= 'z') return value - 'a' + 26;
    if (value >= '0' && value <= '9') return value - '0' + 52;
    if (value == '+') return 62;
    if (value == '/') return 63;
    return -1;
}

size_t decode_base64(const char* encoded, unsigned char* output, size_t capacity)
{
    size_t output_size = 0U;
    std::uint32_t accumulator = 0U;
    unsigned int bits = 0U;
    for (size_t index = 0U; encoded[index] != '\0'; ++index)
    {
        if (encoded[index] == '=')
            break;
        const int value = base64_value(encoded[index]);
        if (value < 0)
            return 0U;
        accumulator = (accumulator << 6U) | static_cast<std::uint32_t>(value);
        bits += 6U;
        if (bits >= 8U)
        {
            bits -= 8U;
            if (output_size >= capacity)
                return 0U;
            output[output_size++] = static_cast<unsigned char>((accumulator >> bits) & 0xffU);
            accumulator = bits == 0U ? 0U : accumulator & ((1U << bits) - 1U);
        }
    }
    return output_size;
}

bool expect(bool condition, const char* message)
{
    if (!condition)
        std::fprintf(stderr, "Cocos image seam failure: %s\n", message);
    return condition;
}

bool state_unchanged(cocos2d::Image& image, unsigned char* data, ssize_t length,
                     int width, int height, cocos2d::Image::Format format)
{
    return image.getData() == data && image.getDataLen() == length &&
           image.getWidth() == width && image.getHeight() == height &&
           image.getFileType() == format;
}

